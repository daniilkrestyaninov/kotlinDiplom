@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AddRecipeScreen(navController: NavController, recipeId: String? = null, draftJson: String? = null) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val service = ApiClient.recipeService

    val db = remember { UmamiDatabase.getDatabase(context) }
    val dao = db.dao()

    // Stepper state
    var currentStep by remember { mutableIntStateOf(0) }
    val stepTitles = listOf("Основа", "Ингредиенты", "Шаги", "Финиш")

    // Form state
    var title by remember { mutableStateOf("") }
    var description by remember { mutableStateOf("") }
    var cookingTime by remember { mutableStateOf("") }
    var portion by remember { mutableStateOf("") }
    var difficulty by remember { mutableStateOf("1") }
    var isPrivate by remember { mutableStateOf(false) }
    var isGenerated by remember { mutableStateOf(false) }
    var isParsed by remember { mutableStateOf(false) }

    // PFC
    var proteins by remember { mutableStateOf("") }
    var fats by remember { mutableStateOf("") }
    var carbohydrates by remember { mutableStateOf("") }
    var calorific by remember { mutableStateOf("") }

    // Image
    var mainImageUri by remember { mutableStateOf<Uri?>(null) }
    var mainImageUrl by remember { mutableStateOf<String?>(null) }
    var isMainImageUploading by remember { mutableStateOf(false) }

    // Steps
    val steps = remember { mutableStateListOf(StepData()) }

    // Metadata
    var categories by remember { mutableStateOf<List<Category>>(emptyList()) }
    var kitchens by remember { mutableStateOf<List<Category>>(emptyList()) }
    var cookingTypes by remember { mutableStateOf<List<Category>>(emptyList()) }
    var celebrations by remember { mutableStateOf<List<Category>>(emptyList()) }
    var ingredients by remember { mutableStateOf<List<Ingredient>>(emptyList()) }

    var selectedCategoryIds by remember { mutableStateOf<Set<String>>(emptySet()) }
    var selectedKitchenId by remember { mutableStateOf<String?>(null) }
    var selectedCookingId by remember { mutableStateOf<String?>(null) }
    var selectedCelebrationId by remember { mutableStateOf<String?>(null) }

    // Ingredient selection
    var ingredientSearch by remember { mutableStateOf("") }
    var selectedIngredients by remember { mutableStateOf<List<SelectedIngredientUi>>(emptyList()) }
    var showIngredientDialog by remember { mutableStateOf(false) }

    var isLoading by remember { mutableStateOf(false) }

    // Picker state
    var showImageSourceDialog by remember { mutableStateOf(false) }
    var imagePickTarget by remember { mutableStateOf("main") }
    var cameraImageUri by remember { mutableStateOf<Uri?>(null) }

    // Helper: Upload Image
    suspend fun uploadImage(uri: Uri, folder: String): String? {
        return withContext(Dispatchers.IO) {
            try {
                android.util.Log.d("AddRecipeScreen", "uploadImage start for uri: $uri, folder: $folder")
                val inputStream = context.contentResolver.openInputStream(uri) ?: return@withContext null
                val bytes = inputStream.readBytes()
                inputStream.close()
                val requestFile = bytes.toRequestBody("image/*".toMediaTypeOrNull())
                val imagePart = MultipartBody.Part.createFormData("image", "photo.jpg", requestFile)
                val folderPart = folder.toRequestBody("text/plain".toMediaTypeOrNull())
                val res = service.uploadImage(imagePart, folderPart)
                android.util.Log.d("AddRecipeScreen", "uploadImage success: ${res.url}")
                res.url
            } catch (e: Exception) {
                android.util.Log.e("AddRecipeScreen", "uploadImage failed for uri: $uri, folder: $folder", e)
                null
            }
        }
    }

    // Launchers
    val galleryLauncher = rememberLauncherForActivityResult(ActivityResultContracts.GetContent()) { uri ->
        uri?.let { 
            if (imagePickTarget == "main") {
                mainImageUri = it
                mainImageUrl = null // Clear old URL so it triggers upload
            } else {
                val idx = imagePickTarget.removePrefix("step_").toIntOrNull()
                if (idx != null && idx < steps.size) {
                    steps[idx] = steps[idx].copy(imageUri = it, uploadedUrl = null) // Clear old step URL
                }
            }
        }
    }
    val cameraLauncher = rememberLauncherForActivityResult(ActivityResultContracts.TakePicture()) { success ->
        if (success && cameraImageUri != null) {
            if (imagePickTarget == "main") {
                mainImageUri = cameraImageUri
                mainImageUrl = null // Clear old URL so it triggers upload
            } else {
                val idx = imagePickTarget.removePrefix("step_").toIntOrNull()
                if (idx != null && idx < steps.size) {
                    steps[idx] = steps[idx].copy(imageUri = cameraImageUri, uploadedUrl = null) // Clear old step URL
                }
            }
        }
    }
    val cameraPermissionLauncher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission()) { granted ->
        if (granted) {
            val uri = createTempImageUri(context)
            cameraImageUri = uri
            cameraLauncher.launch(uri)
        }
    }

    // Load Initial Data
    LaunchedEffect(Unit) {
        try {
            categories = service.getCategories()
            kitchens = service.getKitchens()
            cookingTypes = service.getCookingTypes()
            celebrations = service.getCelebrations()
            ingredients = service.getIngredients()

            if (recipeId != null) {
                // ... (existing edit logic)
                isLoading = true
                val r = service.getRecipeById(recipeId)
                title = r.title ?: ""
                description = r.description ?: ""
                cookingTime = r.cookingTime?.toString() ?: ""
                portion = r.portion?.toString() ?: ""
                calorific = r.calorific?.toString() ?: ""
                proteins = r.proteins?.toString() ?: ""
                fats = r.fats?.toString() ?: ""
                carbohydrates = r.carbohydrates?.toString() ?: ""
                difficulty = r.difficulty ?: "1"
                isPrivate = r.isPrivate ?: false
                isGenerated = r.isGenerated ?: false
                isParsed = r.isParsed ?: false
                mainImageUrl = r.imageUrl
                selectedCategoryIds = r.categories?.map { it.id.toString() }?.toSet() ?: emptySet()
                selectedKitchenId = r.kitchen?.id?.toString()
                selectedCookingId = r.typeCooking?.id?.toString()
                selectedCelebrationId = r.celebration?.id?.toString()
                selectedIngredients = r.ingredients?.map { ing ->
                    val rawUnit = ing.pivot?.unit ?: ""
                    val cleanUnit = if (rawUnit.startsWith("__unit_override:")) rawUnit.substringAfter("__unit_override:") else rawUnit
                    val rawNote = ing.pivot?.note ?: ""
                    val cleanNote = if (rawNote.startsWith("__unit_override:")) "" else rawNote
                    SelectedIngredientUi(id = ing.id?.toIntOrNull(), name = ing.name ?: "", quantity = ing.pivot?.quantity ?: "", unit = cleanUnit, note = cleanNote)
                } ?: emptyList()
                steps.clear()
                r.steps?.sortedBy { it.stepNumber }?.forEach { steps.add(StepData(description = it.description, uploadedUrl = it.imageUrl)) }
                if (steps.isEmpty()) steps.add(StepData())
                isLoading = false
            } else if (draftJson != null || AiDraft.suggestion != null) {
                // ... (existing AI logic)
                val suggestion = if (draftJson != null) Gson().fromJson(draftJson, AiRecipeSuggestion::class.java) else null
                val draft = AiDraft.suggestion
                
                title = suggestion?.title ?: draft?.title ?: ""
                description = suggestion?.description ?: "Рецепт от ИИ-шефа"
                isGenerated = true
                isPrivate = true
                
                val sourceIngs = suggestion?.ingredients?.map { SelectedIngredientUi(name = it.name, quantity = it.quantity, unit = it.unit) }
                    ?: draft?.ingredients?.map { SelectedIngredientUi(name = it.name, quantity = it.quantity ?: "", unit = it.unit ?: "") }
                    ?: emptyList()
                selectedIngredients = sourceIngs
                
                steps.clear()
                (suggestion?.steps?.map { StepData(description = it.description) } 
                    ?: draft?.steps?.map { StepData(description = it.description) } 
                    ?: emptyList()).forEach { steps.add(it) }
                if (steps.isEmpty()) steps.add(StepData())
                AiDraft.suggestion = null
                // Try load from Room Draft
                val savedDraft = dao.getDraft()
                if (savedDraft != null && savedDraft.title.isNotBlank()) {
                    // We could show a dialog, but for now just auto-restore
                    title = savedDraft.title
                    description = savedDraft.description
                    val draftUrl = savedDraft.mainImageUrl
                    if (draftUrl != null && (draftUrl.startsWith("content://") || draftUrl.startsWith("file://"))) {
                        mainImageUrl = null
                        mainImageUri = Uri.parse(draftUrl)
                    } else {
                        mainImageUrl = draftUrl
                        mainImageUri = null
                    }
                    selectedIngredients = Gson().fromJson(savedDraft.ingredientsJson, Array<SelectedIngredientUi>::class.java).toList()
                    val savedSteps = Gson().fromJson(savedDraft.stepsJson, Array<StepData>::class.java).toList()
                    steps.clear()
                    steps.addAll(savedSteps.map { step ->
                        val stepUrl = step.uploadedUrl
                        if (stepUrl != null && (stepUrl.startsWith("content://") || stepUrl.startsWith("file://"))) {
                            step.copy(uploadedUrl = null, imageUri = Uri.parse(stepUrl))
                        } else {
                            step
                        }
                    })
                    Toast.makeText(context, "Черновик восстановлен", Toast.LENGTH_SHORT).show()
                }
            }
        } catch (e: Exception) { isLoading = false }
    }

    // Auto-Save Effect
    LaunchedEffect(
        title,
        description,
        selectedIngredients,
        steps.size,
        mainImageUrl,
        mainImageUri,
        steps.map { it.imageUri?.toString() ?: it.uploadedUrl }
    ) {
        if (recipeId == null && !isGenerated && title.isNotBlank()) {
            val stepsToSave = steps.map { step ->
                if (step.uploadedUrl == null && step.imageUri != null) {
                    step.copy(uploadedUrl = step.imageUri.toString())
                } else {
                    step
                }
            }
            val draft = LocalRecipeDraft(
                title = title,
                description = description,
                ingredientsJson = Gson().toJson(selectedIngredients),
                stepsJson = Gson().toJson(stepsToSave),
                mainImageUrl = mainImageUri?.toString() ?: mainImageUrl
            )
            dao.saveDraft(draft)
        }
    }

    Scaffold(
        topBar = {
            CenterAlignedTopAppBar(
                title = { Text(stepTitles[currentStep], fontFamily = InterFontFamily, fontWeight = FontWeight.Bold) },
                navigationIcon = { IconButton(onClick = { if (currentStep > 0) currentStep-- else navController.popBackStack() }) {
                    Icon(Icons.Default.ArrowBack, contentDescription = null)
                }},
                actions = {
                    Text("${currentStep + 1}/${stepTitles.size}", modifier = Modifier.padding(end = 16.dp), color = Color.Gray, fontSize = 14.sp)
                }
            )
        },
        bottomBar = {
            Surface(shadowElevation = 8.dp) {
                Row(modifier = Modifier.fillMaxWidth().padding(16.dp), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    if (currentStep > 0) {
                        OutlinedButton(onClick = { currentStep-- }, modifier = Modifier.weight(1f).height(50.dp), shape = RoundedCornerShape(12.dp)) {
                            Text("Назад", fontFamily = InterFontFamily)
                        }
                    }
                    Button(
                        onClick = {
                            if (currentStep < 3) {
                                // Validation before next step
                                if (currentStep == 0) {
                                    val timeVal = cookingTime.toIntOrNull()
                                    val portionVal = portion.toIntOrNull()
                                    if (title.isBlank()) {
                                        Toast.makeText(context, "Введите название", Toast.LENGTH_SHORT).show()
                                    } else if (description.isBlank()) {
                                        Toast.makeText(context, "Введите описание", Toast.LENGTH_SHORT).show()
                                    } else if (timeVal == null || timeVal < 1) {
                                        Toast.makeText(context, "Укажите корректное время приготовления (мин)", Toast.LENGTH_SHORT).show()
                                    } else if (portionVal == null || portionVal < 1) {
                                        Toast.makeText(context, "Укажите корректное число порций", Toast.LENGTH_SHORT).show()
                                    } else {
                                        currentStep++
                                    }
                                } else if (currentStep == 1) {
                                    if (selectedIngredients.isEmpty()) {
                                        Toast.makeText(context, "Рецепт должен содержать хотя бы один ингредиент", Toast.LENGTH_SHORT).show()
                                    } else {
                                        currentStep++
                                    }
                                } else if (currentStep == 2) {
                                    if (steps.isEmpty() || steps.any { it.description.isBlank() }) {
                                        Toast.makeText(context, "Опишите все шаги приготовления", Toast.LENGTH_SHORT).show()
                                    } else {
                                        currentStep++
                                    }
                                } else {
                                    currentStep++
                                }
                            } else {
                                // Final Publish
                                scope.launch {
                                    isLoading = true
                                    try {
                                        // 1. Upload images if needed
                                        var mainUrlToUse = mainImageUrl
                                        if (mainUrlToUse != null && (mainUrlToUse.startsWith("content://") || mainUrlToUse.startsWith("file://"))) {
                                            mainUrlToUse = null
                                        }
                                        android.util.Log.d("AddRecipeScreen", "PUBLISH START: mainImageUri=$mainImageUri, mainImageUrl=$mainImageUrl, mainUrlToUse=$mainUrlToUse")
                                        if (mainImageUri != null && mainUrlToUse == null) {
                                            isMainImageUploading = true
                                            android.util.Log.d("AddRecipeScreen", "PUBLISH: Uploading main image $mainImageUri")
                                            mainUrlToUse = uploadImage(mainImageUri!!, "recipes")
                                            mainImageUrl = mainUrlToUse
                                            android.util.Log.d("AddRecipeScreen", "PUBLISH: Uploaded main image URL=$mainUrlToUse")
                                            isMainImageUploading = false
                                        }
                                        val stepsWithUploadedUrls = steps.mapIndexed { index, step ->
                                            var stepUrl = step.uploadedUrl
                                            if (stepUrl != null && (stepUrl.startsWith("content://") || stepUrl.startsWith("file://"))) {
                                                stepUrl = null
                                            }
                                            if (step.imageUri != null && stepUrl == null) {
                                                steps[index] = step.copy(isUploading = true)
                                                val uploaded = uploadImage(step.imageUri!!, "steps")
                                                val updatedStep = step.copy(uploadedUrl = uploaded, isUploading = false)
                                                steps[index] = updatedStep
                                                updatedStep
                                            } else {
                                                step
                                            }
                                        }

                                        val request = CreateRecipeRequest(
                                            title = title,
                                            description = description,
                                            difficulty = difficulty,
                                            imageUrl = mainUrlToUse,
                                            cookingTime = cookingTime.replace(",", ".").toIntOrNull() ?: 0,
                                            portion = portion.replace(",", ".").toIntOrNull() ?: 1,
                                            calorific = calorific.replace(",", ".").toIntOrNull(),
                                            proteins = proteins.replace(",", ".").toFloatOrNull(),
                                            fats = fats.replace(",", ".").toFloatOrNull(),
                                            carbohydrates = carbohydrates.replace(",", ".").toFloatOrNull(),
                                            isPrivate = if (isGenerated || isParsed) true else isPrivate,
                                            isGenerated = isGenerated,
                                            isParsed = isParsed,
                                            kitchenId = selectedKitchenId?.toIntOrNull(),
                                            celebrationId = selectedCelebrationId?.toIntOrNull(),
                                            cookingId = selectedCookingId?.toIntOrNull(),
                                            ingredients = selectedIngredients.map { IngredientInput(id = it.id, name = if (it.id == null) it.name else null, quantity = it.quantity, unit = it.unit, note = it.note) },
                                            steps = stepsWithUploadedUrls.mapIndexed { idx, s -> StepInput(stepNumber = idx + 1, description = s.description, imageUrl = s.uploadedUrl) },
                                            categories = selectedCategoryIds.mapNotNull { it.toIntOrNull() }
                                        )

                                        if (recipeId == null) {
                                            service.createRecipe(request)
                                        } else {
                                            // Send everything in update too
                                            service.updateRecipe(recipeId, mapOf<String, Any?>(
                                                "title" to request.title,
                                                "description" to request.description,
                                                "difficulty" to request.difficulty,
                                                "image_url" to request.imageUrl,
                                                "cooking_time" to request.cookingTime,
                                                "portion" to request.portion,
                                                "calorific" to request.calorific,
                                                "proteins" to request.proteins,
                                                "fats" to request.fats,
                                                "carbohydrates" to request.carbohydrates,
                                                "is_private" to request.isPrivate,
                                                "is_generated" to request.isGenerated,
                                                "is_parsed" to request.isParsed,
                                                "kitchen_id" to request.kitchenId,
                                                "celebration_id" to request.celebrationId,
                                                "cooking_id" to request.cookingId,
                                                "ingredients" to request.ingredients.map { 
                                                    mapOf(
                                                        "id" to it.id,
                                                        "name" to it.name,
                                                        "quantity" to it.quantity,
                                                        "unit" to it.unit,
                                                        "note" to it.note
                                                    ).filterValues { v -> v != null }
                                                },
                                                "steps" to request.steps.map {
                                                    mapOf(
                                                        "step_number" to it.stepNumber,
                                                        "description" to it.description,
                                                        "image_url" to it.imageUrl
                                                    ).filterValues { v -> v != null }
                                                },
                                                "categories" to request.categories
                                            ).filterValues { it != null } as Map<String, Any>)
                                        }

                                        dao.deleteDraft() // Clear draft on success
                                        Toast.makeText(context, "Готово!", Toast.LENGTH_SHORT).show()
                                        navController.popBackStack()
                                    } catch (e: Exception) {
                                        android.util.Log.e("AddRecipeScreen", "Failed to save recipe", e)
                                        val errorMsg = if (e is retrofit2.HttpException) {
                                            try {
                                                val json = e.response()?.errorBody()?.string()
                                                val map = Gson().fromJson(json, Map::class.java)
                                                map["message"]?.toString() ?: "Ошибка сохранения"
                                            } catch (_: Exception) {
                                                "Ошибка сохранения"
                                            }
                                        } else {
                                            "Ошибка сохранения"
                                        }
                                        Toast.makeText(context, errorMsg, Toast.LENGTH_LONG).show()
                                    } finally { isLoading = false }
                                }
                            }
                        },
                        modifier = Modifier.weight(1f).height(50.dp),
                        shape = RoundedCornerShape(12.dp),
                        colors = ButtonDefaults.buttonColors(containerColor = UmamiOrange),
                        enabled = !isLoading
                    ) {
                        if (isLoading) CircularProgressIndicator(color = Color.White, modifier = Modifier.size(20.dp), strokeWidth = 2.dp)
                        else Text(if (currentStep == 3) "Опубликовать" else "Далее", fontFamily = InterFontFamily, fontWeight = FontWeight.Bold)
                    }
                }
            }
        }
    ) { padding ->
        Column(modifier = Modifier.padding(padding).fillMaxSize()) {
            // Step Indicator dots
            Row(modifier = Modifier.fillMaxWidth().padding(vertical = 8.dp), horizontalArrangement = Arrangement.Center) {
                repeat(stepTitles.size) { i ->
                    Box(modifier = Modifier.padding(4.dp).size(8.dp).clip(CircleShape).background(if (i == currentStep) UmamiOrange else Color.LightGray))
                }
            }

            Box(modifier = Modifier.fillMaxSize()) {
                AnimatedContent(targetState = currentStep, transitionSpec = { fadeIn() togetherWith fadeOut() }, label = "FormStep") { step ->
                    when (step) {
                        0 -> BaseInfoStep(title, {title=it}, description, {description=it}, cookingTime, {cookingTime=it}, portion, {portion=it}, difficulty, {difficulty=it}, mainImageUri, mainImageUrl) {
                            imagePickTarget = "main"; showImageSourceDialog = true
                        }
                        1 -> IngredientsStep(selectedIngredients, {selectedIngredients=it}) { showIngredientDialog = true }
                        2 -> StepsStep(steps, { target -> imagePickTarget = target; showImageSourceDialog = true })
                        3 -> FinalStep(isPrivate, {isPrivate=it}, isGenerated, isParsed, selectedCategoryIds, {selectedCategoryIds=it}, categories, selectedKitchenId, {selectedKitchenId=it}, kitchens, selectedCookingId, {selectedCookingId=it}, cookingTypes, selectedCelebrationId, {selectedCelebrationId=it}, celebrations, proteins, {proteins=it}, fats, {fats=it}, carbohydrates, {carbohydrates=it}, calorific, {calorific=it})
                    }
                }
            }
        }
    }

    if (showImageSourceDialog) {
        ImageSourceDialog({ showImageSourceDialog = false }, { galleryLauncher.launch("image/*") }, { cameraPermissionLauncher.launch(Manifest.permission.CAMERA) })
    }

    if (showIngredientDialog) {
        IngredientSelectionDialog(ingredients, selectedIngredients, { selectedIngredients = it }, { showIngredientDialog = false })
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun BaseInfoStep(title: String, onTitle: (String) -> Unit, desc: String, onDesc: (String) -> Unit, time: String, onTime: (String) -> Unit, portion: String, onPortion: (String) -> Unit, difficulty: String, onDifficulty: (String) -> Unit, imageUri: Uri?, imageUrl: String?, onPickImage: () -> Unit) {
    LazyColumn(modifier = Modifier.fillMaxSize(), contentPadding = PaddingValues(20.dp), verticalArrangement = Arrangement.spacedBy(16.dp)) {
        item {
            Box(modifier = Modifier.fillMaxWidth().height(200.dp).clip(RoundedCornerShape(16.dp)).background(Color(0xFFF5F5F5)).clickable { onPickImage() }, contentAlignment = Alignment.Center) {
                if (imageUri != null) {
                    AsyncImage(model = imageUri, contentDescription = null, modifier = Modifier.fillMaxSize(), contentScale = ContentScale.Crop)
                } else if (imageUrl != null) {
                    AsyncImage(model = normalizeImageUrl(imageUrl), contentDescription = null, modifier = Modifier.fillMaxSize(), contentScale = ContentScale.Crop)
                } else {
                    Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Icon(Icons.Default.AddPhotoAlternate, contentDescription = null, modifier = Modifier.size(48.dp), tint = Color.Gray)
                        Text("Добавить главное фото", color = Color.Gray, fontFamily = InterFontFamily)
                    }
                }
            }
        }
        item { CustomTextField("Название", title, onTitle, placeholder = "Напр. Борщ по-домашнему") }
        item { CustomTextField("Описание", desc, onDesc, singleLine = false, minLines = 3) }
        item {
