                            else if (step.uploadedUrl != null) AsyncImage(model = normalizeImageUrl(step.uploadedUrl), contentDescription = null, modifier = Modifier.fillMaxSize(), contentScale = ContentScale.Crop)
                            else Icon(Icons.Default.AddAPhoto, contentDescription = null, tint = Color.LightGray)
                            
                            if (step.isUploading) CircularProgressIndicator(modifier = Modifier.size(32.dp), color = UmamiOrange)
                        }
                        OutlinedTextField(value = step.description, onValueChange = { d -> (steps as MutableList)[index] = step.copy(description = d) }, modifier = Modifier.weight(1f).fillMaxHeight(), placeholder = { Text("Опишите процесс...", fontSize = 13.sp) }, shape = RoundedCornerShape(12.dp))
                    }
                }
            }
        }
        item {
            TextButton(onClick = { (steps as MutableList).add(StepData()) }, modifier = Modifier.fillMaxWidth()) {
                Icon(Icons.Default.Add, contentDescription = null)
                Text("Добавить шаг")
            }
        }
    }
}

