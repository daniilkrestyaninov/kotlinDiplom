@Composable
fun IngredientSelectionDialog(all: List<Ingredient>, selected: List<SelectedIngredientUi>, onUpdate: (List<SelectedIngredientUi>) -> Unit, onDismiss: () -> Unit) {
    var search by remember { mutableStateOf("") }
    AlertDialog(onDismissRequest = onDismiss, title = {Text("Ингредиенты")}, text = {
        Column {
            OutlinedTextField(value = search, onValueChange = {search=it}, placeholder = {Text("Поиск...")}, modifier = Modifier.fillMaxWidth(), shape = RoundedCornerShape(12.dp))
            val filtered = all.filter { it.name.contains(search, true) }.take(20)
            LazyColumn(modifier = Modifier.heightIn(max = 300.dp)) {
                if (search.isNotBlank() && filtered.none { it.name.equals(search, true) }) {
                    item { TextButton(onClick = { onUpdate(selected + SelectedIngredientUi(name = search.trim())); search = "" }) { Icon(Icons.Default.Add, null); Text("Добавить \"$search\"") } }
                }
                items(filtered) { ing ->
                    val isAdded = selected.any { it.id == ing.id.toIntOrNull() }
                    Row(modifier = Modifier.fillMaxWidth().clickable { 
                        if(!isAdded) {
                            val suggestedUnit = INGREDIENT_UNIT_SUGGESTIONS.entries.find { it.key.equals(ing.name, ignoreCase = true) }?.value ?: ""
                            onUpdate(selected + SelectedIngredientUi(id = ing.id.toIntOrNull(), name = ing.name, unit = suggestedUnit))
                        }
                    }.padding(8.dp), verticalAlignment = Alignment.CenterVertically) {
                        Text(ing.name, modifier = Modifier.weight(1f))
                        if(isAdded) Icon(Icons.Default.Check, null, tint = UmamiOrange)
                    }
                }
            }
        }
    }, confirmButton = { TextButton(onClick = onDismiss) {Text("Готово", color = UmamiOrange)} })
}

private fun createTempImageUri(context: Context): Uri {
    val imagesDir = File(context.cacheDir, "images")
    if (!imagesDir.exists()) {
        imagesDir.mkdirs()
    }
    val file = File.createTempFile("recipe_photo_", ".jpg", imagesDir)
    return FileProvider.getUriForFile(context, "${context.packageName}.provider", file)
}
