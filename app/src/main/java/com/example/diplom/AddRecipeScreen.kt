                                Icon(Icons.Default.RemoveCircleOutline, contentDescription = null, tint = Color.LightGray)
                            }
                        }
                    }
                    Row(modifier = Modifier.fillMaxWidth().height(100.dp), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                        Box(modifier = Modifier.size(100.dp).clip(RoundedCornerShape(12.dp)).background(Color(0xFFF9F9F9)).clickable { onPickImage("step_$index") }, contentAlignment = Alignment.Center) {
