            DropdownMenuItem(text = {Text("Не выбрано")}, onClick = { onSelected(null); expanded = false })
            items.forEach { item ->
                DropdownMenuItem(text = {Text(item.name)}, onClick = { onSelected(item.id.toString()); expanded = false })
            }
        }
    }
}

