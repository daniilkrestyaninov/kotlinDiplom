    var expanded by remember { mutableStateOf(false) }
    val selectedItem = items.find { it.id.toString() == selectedId }
    
    ExposedDropdownMenuBox(expanded = expanded, onExpandedChange = { expanded = it }) {
        OutlinedTextField(value = selectedItem?.name ?: "Не выбрано", onValueChange = {}, readOnly = true, label = {Text(label)}, modifier = Modifier.fillMaxWidth().menuAnchor(), shape = RoundedCornerShape(12.dp), trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = expanded) })
